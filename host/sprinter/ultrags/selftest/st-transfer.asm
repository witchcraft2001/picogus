; POSITIVE: 1024-byte transfer split into profile chunks; FIXED/ALIAS/
; proven STACK variants are selected by runner inputs at B300h.
; FIXED/ALIAS can receive an NMI with the ordinary SP; STACK's proven
; profile excludes NMI throughout the swapped-SP interval.
	INCLUDE "st-head.inc"
	ld a,(0xB300)
	call UG_CPU_PROFILE
	jp c,st_failA
	ld a,(0xB301)
	ld (UG_METHOD),a
	ld a,(0xB302)
	ld (UG_NMI_PROFILE),a
	ld a,0xED
	ld (0x66),a
	ld a,0x45
	ld (0x67),a
	xor a
	ld hl,0x2A0
	call UG_OPEN
	jp c,st_failA
	or a
	jp nz,st_fail
	ld a,1
	call UG_FRAME_CRC
	jp c,st_failA
	or a
	jp nz,st_fail
	ld de,UG_ARGBUF
	xor a
	ld (de),a
	inc de
	ld hl,1024
	ld bc,0
	call PUT_LE32
	ld a,UG_OP_ALLOC
	ld hl,UG_ARGBUF
	ld bc,5
	ld de,ST_RESP
	ld ix,64
	call UG_RPC
	jp c,st_failA
	ld hl,(ST_RESP)
	ld (ST_RESULT+4),hl
	ld hl,0xB400
	ld bc,1024
.fill:	ld (hl),c
	inc hl
	dec bc
	ld a,b
	or c
	jr nz,.fill
	xor a
	ld (UG_OFFSET),a
	ld (UG_OFFSET+1),a
	ld (UG_OFFSET+2),a
	ld (UG_OFFSET+3),a
	ld hl,(ST_RESULT+4)
	ld de,0xB400
	ld bc,1024
	xor a
	call UG_WRITE
	jp c,st_failA
	or a
	jp nz,st_fail
	; STACK is write-only. Read back through FIXED while retaining the
	; known-NMI STACK write/context test above.
	ld a,(UG_METHOD)
	cp 2
	jr nz,.read
	xor a
	ld (UG_METHOD),a
.read:
	ld hl,(ST_RESULT+4)
	ld de,0xB000
	ld bc,1024
	xor a
	call UG_READ
	jp c,st_failA
	or a
	jp nz,st_fail
	ld hl,0xB400
	ld de,0xB000
	ld bc,1024
.cmp:	ld a,(de)
	cp (hl)
	jp nz,st_fail
	inc de
	inc hl
	dec bc
	ld a,b
	or c
	jr nz,.cmp
	ld hl,0xB000
	call UG_SNAPSHOT
	jp c,st_failA
	or a
	jp nz,st_fail
	ld a,UG_XC_CLEAR_ERRORS
	call UG_XCTRL
	jp c,st_failA
	or a
	jp nz,st_fail
	ld hl,.desc
	call UG_GS_COMMAND
	jp c,st_failA
	or a
	jp nz,st_fail
	ld hl,.desc
	call UG_GS_COMMAND
	jp c,st_failA
	or a
	jp nz,st_fail
	ld de,UG_ARGBUF
	ld hl,(ST_RESULT+4)
	call PUT_LE16
	ld a,UG_OP_FREE
	ld hl,UG_ARGBUF
	ld bc,2
	ld de,ST_RESP
	ld ix,64
	call UG_RPC
	jp c,st_failA
	call UG_CLOSE
	jp st_pass
.desc:	DB 0x6A,1,0x5A,0
	DW 0
	DB 1
	DW ST_RESP
	INCLUDE "st-tail.inc"
