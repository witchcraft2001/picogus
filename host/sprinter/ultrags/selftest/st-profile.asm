; POSITIVE: distinct CPU profiles and unknown-mode FIXED fallback.
	INCLUDE "st-head.inc"
	ld a,1
	call UG_CPU_PROFILE
	jp c,st_failA
	or a
	jp nz,st_fail
	ld hl,(UG_CHUNK)
	ld de,32
	or a
	sbc hl,de
	jp nz,st_fail
	ld a,2
	call UG_CPU_PROFILE
	jp c,st_failA
	ld hl,(UG_CHUNK)
	ld de,8
	or a
	sbc hl,de
	jp nz,st_fail
	ld a,2
	ld (UG_METHOD),a
	ld a,0xFF
	call UG_CPU_PROFILE
	jp c,st_failA
	ld a,(UG_PROFILE)
	or a
	jp nz,st_fail
	ld a,(UG_METHOD)
	or a
	jp nz,st_fail
	ld a,1
	ld (UGXFER.DIR),a
	ld a,1
	call UG_CPU_PROFILE
	jp nc,st_fail
	cp UG_ERR_BUSY
	jp nz,st_fail
	xor a
	ld (UGXFER.DIR),a
	jp st_pass
	INCLUDE "st-tail.inc"
