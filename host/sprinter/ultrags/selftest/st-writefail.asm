; POSITIVE fault paths: runner input B303h chooses expected error; card
; injects a short BEGIN response or a PSRAM commit failure. Cleanup must
; preserve the original LAST_ERROR/SOURCE, release pins, and permit FREE.
	INCLUDE "st-head.inc"
	xor a
	ld hl,0x2A0
	call UG_OPEN
	jp c,st_failA
	ld de,UG_ARGBUF
	xor a
	ld (de),a
	inc de
	ld hl,64
	ld bc,0
	call PUT_LE32
	ld a,UG_OP_ALLOC
	ld hl,UG_ARGBUF
	ld bc,5
	ld de,ST_RESP
	ld ix,64
	call UG_RPC
	jp c,st_failA
	ld hl,(ST_RESP)
	ld (ST_RESULT+4),hl
	xor a
	ld (UG_OFFSET),a
	ld (UG_OFFSET+1),a
	ld (UG_OFFSET+2),a
	ld (UG_OFFSET+3),a
	ld de,ST_TX
	ld bc,64
	xor a
	call UG_WRITE
	jp nc,st_fail
	ld b,a
	ld a,(0xB303)
	cp b
	jp nz,st_fail
	ld a,(UG_LAST_ERROR)
	cp b
	jp nz,st_fail
	ld a,(0xB304)
	ld b,a
	ld a,(UG_LAST_SOURCE)
	cp b
	jp nz,st_fail
	ld de,UG_ARGBUF
	ld hl,(ST_RESULT+4)
	call PUT_LE16
	ld a,UG_OP_FREE
	ld hl,UG_ARGBUF
	ld bc,2
	ld de,ST_RESP
	ld ix,64
	call UG_RPC
	jp c,st_failA
	call UG_CLOSE
	jp st_pass
	INCLUDE "st-tail.inc"
