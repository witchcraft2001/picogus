"""Print the GF(2) operators used by the Z80 verified dump CRC combiner."""
def multiply(matrix, vector):
    result = 0
    for column in matrix:
        if vector & 1:
            result ^= column
        vector >>= 1
    return result

def operators():
    matrix = [0xEDB88320] + [1 << bit for bit in range(31)]
    for _ in range(3):
        matrix = [multiply(matrix, column) for column in matrix]
    for _ in range(11):
        yield matrix
        matrix = [multiply(matrix, column) for column in matrix]

def assembly():
    lines = ['; SPDX-License-Identifier: GPL-2.0-or-later',
             '; Generated by tools/ultrags/gen-crc-combine.py; byte-length powers 1..1024.',
             'UG_CRC_COMBINE_POWERS:']
    for matrix in operators():
        for start in range(0, 32, 4):
            lines.append('    DD ' + ','.join(f'0x{v:08X}' for v in matrix[start:start+4]))
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    print(assembly(), end='')
